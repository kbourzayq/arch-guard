using System.Collections.Immutable;
using ArchitectureGuardian.Analysis.Dependencies;
using ArchitectureGuardian.Analysis.Workspaces;
using ArchitectureGuardian.Analyzers;
using ArchitectureGuardian.Core.Analysis;
using ArchitectureGuardian.Core.Policies;
using ArchitectureGuardian.Core.Rules;
using ArchitectureGuardian.Tests.Workspaces;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using Xunit;
using DiagnosticSeverity = ArchitectureGuardian.Core.Diagnostics.DiagnosticSeverity;

namespace ArchitectureGuardian.Tests.Dependencies;

/// <summary>Checks both AG006 engines against the same real compilation and explicit source ownership.</summary>
/// <param name="fixture">Restored workspace inputs.</param>
[Trait("Category", "Integration")]
public sealed class DomainInfrastructureParityTests(ModularWorkspaceFixture fixture) : IClassFixture<ModularWorkspaceFixture>
{
    /// <summary>Aliases, generated/partial sources, framework types and same-namespace uses share restriction meanings.</summary>
    /// <param name="restrictAssembly">Also checks the bound framework assembly through the source layer.</param>
    /// <param name="forwardSlashInput">Supplies forward slashes even when the host uses backslashes.</param>
    [Theory]
    [InlineData(false, false)]
    [InlineData(true, false)]
    [InlineData(false, true)]
    [InlineData(true, true)]
    public async Task Both_engines_resolve_the_same_forbidden_symbols_and_preserve_spans(bool restrictAssembly, bool forwardSlashInput)
    {
        var root = Path.Combine(fixture.Root, "ModularMonolith");
        var project = Path.Combine(root, "src", "Orders", "Orders.Application", "Orders.Application.csproj");
        var inputPath = forwardSlashInput ? project.Replace('\\', '/') : project;
        var source = Path.Combine(Path.GetDirectoryName(project)!, "Restricted.cs");
        var generated = Path.Combine(Path.GetDirectoryName(project)!, "Restricted.g.cs");
        await File.WriteAllTextAsync(source, """
            global using Api = System.Text.StringBuilder;
            global using ApiList = System.Collections.Generic.List<System.Text.StringBuilder>;
            global using Ns = System.Text;
            public partial class Uses {
                public Api Text;
                public ApiList Texts;
                public Ns.StringBuilder Other;
                public System.TextLike.StringBuilder Allowed;
                public string Spelling => "System.Text.StringBuilder";
            }
            namespace System.TextLike { public class StringBuilder { } }
            namespace System.Text.Custom { public class Local { public Local Other; } }
            """);
        await File.WriteAllTextAsync(generated, """
            // <auto-generated/>
            public partial class Uses { public System.Text.StringBuilder Generated; }
            """);
        try
        {
            using var workspace = await new MSBuildWorkspaceLoader().LoadAsync(new(inputPath, isTrusted: true));
            Assert.Equal(AnalysisStatus.Completed, workspace.Status);
            // Roslyn normalizes host paths; the fixture's assembly identity is independent of input path spelling.
            var sourceProject = Assert.Single(workspace.Solution!.Projects, input => input.AssemblyName == "Orders.Application");
            var sourceCompilation = (await sourceProject.GetCompilationAsync())!;
            var frameworkAssembly = sourceCompilation.GetTypeByMetadataName("System.Text.StringBuilder")!.ContainingAssembly.Name;
            var policy = new ArchitecturePolicy([new("All", ["**/*.csproj"])],
                [new("Business", ["**/*.csproj"], domainInfrastructure: new(
                    forbiddenAssemblies: restrictAssembly ? [frameworkAssembly] : [], forbiddenNamespaces: ["System.Text"],
                    allowedNamespaces: ["System.Text.Custom"]))],
                new Dictionary<string, DiagnosticSeverity> { ["AG006"] = DiagnosticSeverity.Error });
            var context = await new DependencyGraphBuilder().BuildAsync(workspace, root, policy);
            Assert.Equal(AnalysisStatus.Completed, context.Status);
            var standalone = await new DomainInfrastructureRule().EvaluateAsync(context);
            Assert.Equal(AnalysisStatus.Completed, standalone.Status);
            Assert.NotEmpty(standalone.Violations);
            Assert.DoesNotContain(standalone.Violations, item => item.Target.Symbol == "System.Text.Custom.Local");
            Assert.Contains(standalone.Violations.SelectMany(item => item.Evidence), fact => fact.Location!.Path.EndsWith("Restricted.g.cs", StringComparison.Ordinal));
            Assert.DoesNotContain(standalone.Violations, item => item.Target.Symbol!.Contains("TextLike", StringComparison.Ordinal));

            var snapshot = "<ArchitectureGuardian version='1'><Module id='All'/>"
                + $"<Layer id='Business' infrastructureNamespaces='System.Text' infrastructureAssemblies='{(restrictAssembly ? frameworkAssembly : "")}' allowedInfrastructureNamespaces='System.Text.Custom'/>"
                + string.Concat(context.Repository!.Projects.Select(item => $"<Assembly name='{item.Assembly.Name}' module='All' layer='Business'/>"))
                + "</ArchitectureGuardian>";
            var compiler = new List<Microsoft.CodeAnalysis.Diagnostic>();
            foreach (var input in workspace.Solution!.Projects)
            {
                var compilation = (await input.GetCompilationAsync())!;
                var driver = compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new DependencyAnalyzer()),
                    new AnalyzerOptions(ImmutableArray.Create<AdditionalText>(new Snapshot(snapshot))));
                compiler.AddRange(await driver.GetAnalyzerDiagnosticsAsync());
            }

            Assert.All(compiler, item => Assert.Equal("AG006", item.Id));
            Assert.All(compiler, item => Assert.True(item.Location.IsInSource));
            foreach (var symbol in new[] { "System.Text.StringBuilder" })
            {
                Assert.Contains(standalone.Violations, item => item.Target.Symbol == symbol
                    && item.Message.Contains("layers.Business.domainInfrastructure.forbiddenNamespaces restriction 'System.Text'", StringComparison.Ordinal));
                Assert.Contains(compiler, item => item.GetMessage().Contains("uses infrastructure symbol '" + symbol + "'", StringComparison.Ordinal)
                    && item.GetMessage().Contains("layers.Business.domainInfrastructure.forbiddenNamespaces restriction 'System.Text'", StringComparison.Ordinal));
            }

            if (restrictAssembly)
            {
                var restriction = $"layers.Business.domainInfrastructure.forbiddenAssemblies restriction '{frameworkAssembly}'";
                Assert.Contains(standalone.Violations, item => item.Target.Symbol == "System.Text.StringBuilder"
                    && item.Message.Contains(restriction, StringComparison.Ordinal));
                Assert.Contains(compiler, item => item.GetMessage().Contains("uses infrastructure symbol 'System.Text.StringBuilder'", StringComparison.Ordinal)
                    && item.GetMessage().Contains(restriction, StringComparison.Ordinal));
                // The explicit string keyword above binds to the same assembly as System.String.
                Assert.Contains(compiler, item => item.Location.SourceTree!.FilePath.EndsWith("Restricted.cs", StringComparison.Ordinal)
                    && item.Location.SourceTree.GetText().ToString(item.Location.SourceSpan) == "string"
                    && item.GetMessage().Contains(restriction, StringComparison.Ordinal));
                Assert.Contains(standalone.Violations, item => item.Target.Symbol is "string" or "System.String"
                    && item.Message.Contains(restriction, StringComparison.Ordinal));
            }

            Assert.DoesNotContain(compiler, item => item.GetMessage().Contains("TextLike", StringComparison.Ordinal));
            Assert.DoesNotContain(compiler, item => item.GetMessage().Contains("System.Text.Custom.Local", StringComparison.Ordinal));
            Assert.Contains(compiler, item => item.Location.SourceTree!.FilePath.EndsWith("Restricted.g.cs", StringComparison.Ordinal));
        }
        finally
        {
            File.Delete(source);
            File.Delete(generated);
        }
    }

    private sealed class Snapshot(string text) : AdditionalText
    {
        public override string Path => "architecture.guardian.compiler.xml";
        public override SourceText GetText(CancellationToken cancellationToken = default) => SourceText.From(text);
    }
}
