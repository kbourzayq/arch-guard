/// <summary>Exercises compiler semantics through Microsoft.CodeAnalysis.Testing and independent compilation drivers.</summary>
public sealed class DependencyAnalyzerTests
{
    private const string Policy = """
        <ArchitectureGuardian version="1">
          <Module id="Orders" /><Module id="Billing" />
          <Layer id="Application" /><Layer id="Infrastructure" />
          <Assembly name="Orders.Application" module="Orders" layer="Application" />
          <Assembly name="Billing.Application" module="Billing" layer="Infrastructure" />
        </ArchitectureGuardian>
        """;
    private const string Billing = """
        namespace Billing {
          public class Service { public static void Run() { } }
          public class CatalogDbContext { public static void Save() { } }
          public class Box<T> { }
          public class TagAttribute : System.Attribute { }
        }
        """;

    /// <summary>Resolves aliases, generic arguments, attributes and imported static members by symbol, rather than source spelling.</summary>
    /// <param name="source">A compilable use of a forbidden assembly with its exact evidence span marked.</param>
    [Theory]
    [InlineData("public class Order : Billing.{|#0:Service|} { }")]
    [InlineData("using Alias = Billing.Service; public class Order : {|#0:Alias|} { }")]
    [InlineData("global using Alias = Billing.Service; public class Order : {|#0:Alias|} { }")]
    [InlineData("global using Billing; public class Order : {|#0:Service|} { }")]
    [InlineData("public class Order : Billing.{|#0:Box<int>|} { }")]
    [InlineData("public class Order : System.Collections.Generic.List<Billing.{|#0:Service|}> { }")]
    [InlineData("[Billing.{|#0:Tag|}] public class Order { }")]
    [InlineData("using static Billing.Service; public class Order { public void Go() { {|#0:Run|}(); } }")]
    public async Task Semantic_uses_keep_canonical_rule_meanings(string source)
    {
        var test = await CreateAsync(source);
        ExpectPair(test, 0);
        await test.RunAsync();
    }

    /// <summary>Reports each partial declaration's actual dependency location without relying on declaration order.</summary>
    [Fact]
    public async Task Partial_types_and_multiple_documents_keep_source_evidence()
    {
        var test = await CreateAsync("public partial class Order { public Billing.{|#0:Service|} Get() => null; }");
        test.TestState.Sources.Add(("Second.cs", "public partial class Order { public Billing.{|#1:Box<int>|} Other() => null; }"));
        ExpectPair(test, 0);
        ExpectPair(test, 1);
        await test.RunAsync();
    }

    /// <summary>Includes generator-style files and generated-code attributes in the explicit compiler scope.</summary>
    /// <param name="path">The generated source's host path.</param>
    /// <param name="prefix">A generator marker recognized by Roslyn.</param>
    [Theory]
    [InlineData("Generated.g.cs", "// <auto-generated/>\n")]
    [InlineData("Attributed.cs", "[System.CodeDom.Compiler.GeneratedCode(\"fixture\", \"1\")] ")]
    public async Task Generated_sources_are_analyzed(string path, string prefix)
    {
        var test = await CreateAsync("");
        test.TestState.Sources.Add((path, prefix + "public class Order : Billing.{|#0:Service|} { }"));
        ExpectPair(test, 0);
        await test.RunAsync();
    }

    /// <summary>Uses assembly ownership even when the dependency is another source project rather than a DLL.</summary>
    [Fact]
    public async Task Multi_project_references_use_the_same_policy()
    {
        var test = await CreateAsync("public class Order : Billing.{|#0:Service|} { }");
        test.TestState.AdditionalReferences.Clear();
        var billing = test.TestState.AdditionalProjects["Billing.Application", LanguageNames.CSharp];
        billing.Sources.Add(Billing);
        billing.AdditionalFiles.Add(("architecture.guardian.compiler.xml", Policy));
        test.TestState.AdditionalProjectReferences.Add("Billing.Application");
        ExpectPair(test, 0);
        await test.RunAsync();
    }

    /// <summary>Checks exact contract permissions, same ownership and independent directional layer decisions.</summary>
    /// <param name="module">The target module's ownership.</param>
    /// <param name="layer">The target layer's ownership.</param>
    /// <param name="permission">The outgoing module permission.</param>
    /// <param name="contract">The target's optional public contract.</param>
    /// <param name="moduleViolation">Whether AG001 is expected.</param>
    /// <param name="layerViolation">Whether AG002 is expected.</param>
    [Theory]
    [InlineData("Orders", "Application", "", "", false, false)]
    [InlineData("Billing", "Infrastructure", "module:Billing", "", false, true)]
    [InlineData("Billing", "Application", "contract:Billing/api", "api", false, false)]
    [InlineData("Billing", "Application", "", "api", true, false)]
    public async Task Permissions_remain_independent(string module, string layer, string permission, string contract,
        bool moduleViolation, bool layerViolation)
    {
        var policy = Policy.Replace("<Module id=\"Orders\" />", $"<Module id=\"Orders\" allows=\"{permission}\" />", StringComparison.Ordinal)
            .Replace("module=\"Billing\" layer=\"Infrastructure\"", $"module=\"{module}\" layer=\"{layer}\"" +
                (contract.Length == 0 ? "" : $" contract=\"{contract}\""), StringComparison.Ordinal);
        var test = await CreateAsync("public class Order : Billing.{|#0:Service|} { }", policy);
        if (moduleViolation) { test.ExpectedDiagnostics.Add(Result("AG001", 0)); }
        if (layerViolation) { test.ExpectedDiagnostics.Add(Result("AG002", 0)); }
        if (module != "Orders" && contract.Length == 0) { test.ExpectedDiagnostics.Add(Result("AG004", 0)); }
        await test.RunAsync();
    }

    /// <summary>Lets the compiler host apply severities and suppression through standard editorconfig settings.</summary>
    [Fact]
    public async Task Host_options_control_severity_and_editorconfig_suppresses_rules()
    {
        var test = await CreateAsync("public class Order : Billing.{|#0:Service|} { }");
        test.TestState.AnalyzerConfigFiles.Add(("/.editorconfig", "root = true\n\n[*]\ndotnet_diagnostic.AG001.severity = error\ndotnet_diagnostic.AG002.severity = none\ndotnet_diagnostic.AG004.severity = none\n"));
        // The testing driver applies host severity through CompilationOptions; the SDK smoke test checks editorconfig promotion.
        test.SolutionTransforms.Add((solution, id) => solution.WithProjectCompilationOptions(id,
            solution.GetProject(id)!.CompilationOptions!.WithSpecificDiagnosticOptions(
                ImmutableDictionary<string, ReportDiagnostic>.Empty.Add("AG001", ReportDiagnostic.Error))));
        test.ExpectedDiagnostics.Add(new DiagnosticResult("AG001", DiagnosticSeverity.Error).WithLocation(0));
        await test.RunAsync();
    }

    /// <summary>Invalid, ambiguous or absent policy must report unavailable analysis, never a clean result or analyzer exception.</summary>
    /// <param name="policy">An invalid compiler snapshot, or null for a missing file.</param>
    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("<ArchitectureGuardian version='2' />")]
    [InlineData("<ArchitectureGuardian version='1' unknown='x' />")]
    [InlineData("<!DOCTYPE x [<!ENTITY x 'bad'>]><ArchitectureGuardian version='1'>&x;</ArchitectureGuardian>")]
    [InlineData("<ArchitectureGuardian version='1'><Module id='A'/><Module id='A'/></ArchitectureGuardian>")]
    [InlineData("<ArchitectureGuardian version='1'><Assembly name='Orders.Application' module='Missing' layer='Missing'/></ArchitectureGuardian>")]
    [InlineData("<ArchitectureGuardian version='1'><Module id='A' allows='module:Missing'/></ArchitectureGuardian>")]
    public async Task Invalid_policy_reports_configuration_diagnostic(string? policy)
    {
        var test = await CreateAsync("public class Order { }", policy ?? Policy);
        if (policy is null) { test.TestState.AdditionalFiles.Clear(); }
        test.ExpectedDiagnostics.Add(new DiagnosticResult("AG000", DiagnosticSeverity.Error));
        await test.RunAsync();
    }

    /// <summary>Rejects duplicate snapshots and assembly-name drift as explicit configuration errors.</summary>
