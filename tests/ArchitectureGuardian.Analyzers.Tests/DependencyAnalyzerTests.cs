    {
        var test = await CreateAsync("using Store = Billing.CatalogDbContext; public class CatalogDbContext { } public class Order : CatalogDbContext { }");
        await test.RunAsync();
    }

    /// <summary>Reuses one analyzer concurrently with different snapshots without leaking policy state between compilations.</summary>
    [Fact]
    public async Task Concurrent_compilations_are_isolated_and_repeatable()
    {
        var analyzer = new DependencyAnalyzer();
        var permitted = Policy.Replace("<Module id=\"Orders\" />", "<Module id=\"Orders\" allows=\"module:Billing\" />", StringComparison.Ordinal)
            .Replace("<Layer id=\"Application\" />", "<Layer id=\"Application\" allows=\"Infrastructure\" />", StringComparison.Ordinal);
        var runs = Enumerable.Range(0, 12).Select(async index =>
        {
            var driver = await DriverAsync(analyzer, index % 2 == 0 ? Policy : permitted);
            var diagnostics = await driver.GetAnalyzerDiagnosticsAsync();
            Assert.Equal(index % 2 == 0 ? new[] { "AG001", "AG002", "AG004" } : new[] { "AG004" }, diagnostics.Select(item => item.Id).Order().ToArray());
        });
        await Task.WhenAll(runs);
    }

    /// <summary>Propagates cancellation from the host and from AdditionalText reads instead of translating it into AG000.</summary>
    [Fact]
    public async Task Cancellation_is_preserved()
    {
        using var cancellation = new CancellationTokenSource();
        var driver = await DriverAsync(new DependencyAnalyzer(), Policy);
        cancellation.Cancel();
        await Assert.ThrowsAnyAsync<OperationCanceledException>(() => driver.GetAnalyzerDiagnosticsAsync(cancellation.Token));
        using var duringRead = new CancellationTokenSource();
        var readDriver = await DriverAsync(new DependencyAnalyzer(), Policy, duringRead);
        await Assert.ThrowsAnyAsync<OperationCanceledException>(() => readDriver.GetAnalyzerDiagnosticsAsync(duringRead.Token));
    }

    private static async Task<CSharpAnalyzerTest<DependencyAnalyzer, DefaultVerifier>> CreateAsync(string source, string policy = Policy)
    {
        var test = new CSharpAnalyzerTest<DependencyAnalyzer, DefaultVerifier>
        {
            TestCode = source,
            ReferenceAssemblies = ReferenceAssemblies.Net.Net80,
            TestBehaviors = TestBehaviors.SkipGeneratedCodeCheck | TestBehaviors.SkipSuppressionCheck,
        };
        test.SolutionTransforms.Add((solution, id) => solution.WithProjectAssemblyName(id, "Orders.Application")
            .WithProjectParseOptions(id, new CSharpParseOptions(LanguageVersion.CSharp12)));
        test.TestState.AdditionalFiles.Add(("architecture.guardian.compiler.xml", policy));
        test.TestState.AdditionalReferences.Add(await BillingReferenceAsync());
        return test;
    }

    private static async Task<MetadataReference> BillingReferenceAsync()
    {
        // Compile against the same reference pack used by the semantic harness.
        var references = await ReferenceAssemblies.Net.Net80.ResolveAsync(LanguageNames.CSharp, CancellationToken.None);
        var billing = CSharpCompilation.Create("Billing.Application", [CSharpSyntaxTree.ParseText(Billing)], references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        using var output = new MemoryStream();
        var result = billing.Emit(output);
        Assert.True(result.Success, string.Join(Environment.NewLine, result.Diagnostics));
        return MetadataReference.CreateFromImage(output.ToArray());
    }

    private static DiagnosticResult Result(string id, int location) => new DiagnosticResult(id, DiagnosticSeverity.Warning).WithLocation(location);

    private static void ExpectPair(CSharpAnalyzerTest<DependencyAnalyzer, DefaultVerifier> test, int location)
    {
        test.ExpectedDiagnostics.Add(Result("AG001", location));
        test.ExpectedDiagnostics.Add(Result("AG002", location));
        test.ExpectedDiagnostics.Add(Result("AG004", location));
    }

    private static async Task<CompilationWithAnalyzers> DriverAsync(DependencyAnalyzer analyzer, string policy, CancellationTokenSource? cancelOnRead = null)
    {
        var compilation = CSharpCompilation.Create("Orders.Application",
            [CSharpSyntaxTree.ParseText("public class Order : Billing.Service { }")],
            [MetadataReference.CreateFromFile(typeof(object).Assembly.Location), await BillingReferenceAsync()],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        return compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(analyzer),
            new AnalyzerOptions(ImmutableArray.Create<AdditionalText>(new PolicyText(policy, cancelOnRead))));
    }

    /// <summary>Supplies in-memory host policy and optionally triggers cancellation while reading it.</summary>
    private sealed class PolicyText(string policy, CancellationTokenSource? cancelOnRead) : AdditionalText
    {
        public override string Path => "architecture.guardian.compiler.xml";
        public override SourceText GetText(CancellationToken cancellationToken = default)
        {
            cancelOnRead?.Cancel();
            cancellationToken.ThrowIfCancellationRequested();
            return SourceText.From(policy);
        }
    }
}
